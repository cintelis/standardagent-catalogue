// Writes the generated TypeScript module that the package imports. `tsc` runs
// after this script. This package has no Rust: its engine is TypeScript.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const generatedDir = `${root}src/generated`;
mkdirSync(generatedDir, { recursive: true });

// Copy the name and version from package.json, so that the package's __meta
// export always agrees with its manifest.
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'));
writeFileSync(
  `${generatedDir}/package-info.ts`,
  `// Generated by scripts/build.mjs from package.json. Do not edit.\n` +
    `export const PACKAGE_ID = ${JSON.stringify(pkg.name)};\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export const PACKED_AT = ${Date.now()};\n`,
);

console.log(`Wrote package-info.ts for ${pkg.name}@${pkg.version}`);
