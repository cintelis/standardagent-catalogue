// Builds the Rust crate to WebAssembly and writes the two generated TypeScript
// modules that the package imports. `tsc` runs after this script.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const rustDir = `${root}rust`;
const generatedDir = `${root}src/generated`;
const target = 'wasm32-unknown-unknown';

// 1. Compile Rust to WebAssembly.
try {
  execFileSync('cargo', ['build', '--release', '--target', target], {
    cwd: rustDir,
    stdio: 'inherit',
  });
} catch {
  console.error(
    `\nThe Rust build failed. If the ${target} target is missing, add it with:\n` +
      `  rustup target add ${target}\n`,
  );
  process.exit(1);
}

mkdirSync(generatedDir, { recursive: true });

// 2. Embed the .wasm file in a TypeScript module as base64.
//    An npm package cannot rely on every runtime loading a .wasm file from
//    disk, so the bytes travel inside the JavaScript.
const wasm = readFileSync(`${rustDir}/target/${target}/release/text_stats.wasm`);
writeFileSync(
  `${generatedDir}/wasm-bytes.ts`,
  `// Generated by scripts/build.mjs from rust/src/lib.rs. Do not edit.\n` +
    `export const WASM_BASE64 =\n  '${wasm.toString('base64')}';\n`,
);

// 3. Copy the name and version from package.json, so that the package's
//    __meta export always agrees with its manifest.
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'));
writeFileSync(
  `${generatedDir}/package-info.ts`,
  `// Generated by scripts/build.mjs from package.json. Do not edit.\n` +
    `export const PACKAGE_ID = ${JSON.stringify(pkg.name)};\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export const PACKED_AT = ${Date.now()};\n`,
);

console.log(`Embedded text_stats.wasm (${wasm.length} bytes) for ${pkg.name}@${pkg.version}`);
