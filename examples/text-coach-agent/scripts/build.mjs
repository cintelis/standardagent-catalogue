// Builds the Rust crate to WebAssembly, writes the two generated TypeScript
// modules that the package imports, and copies the .wasm file into dist/.
// `tsc` runs after this script.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const rustDir = `${root}rust`;
const generatedDir = `${root}src/generated`;
const distDir = `${root}dist`;
const target = 'wasm32-unknown-unknown';

// 1. Compile Rust to WebAssembly.
//    A compiled module holds the paths of its source files, for panic
//    messages. These flags swap the two folders that differ from one machine
//    to the next for fixed names, so that the module does not carry the
//    builder's home folder, and the same source gives the same bytes.
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), '.cargo');
const remap = [
  `--remap-path-prefix=${cargoHome}=/cargo`,
  `--remap-path-prefix=${root.replace(/[\\/]$/, '')}=/src`,
];
try {
  execFileSync('cargo', ['build', '--release', '--locked', '--target', target], {
    cwd: rustDir,
    stdio: 'inherit',
    env: { ...process.env, RUSTFLAGS: [process.env.RUSTFLAGS, ...remap].filter(Boolean).join(' ') },
  });
} catch {
  console.error(
    `\nThe Rust build failed. If the ${target} target is missing, add it with:\n` +
      `  rustup target add ${target}\n`,
  );
  process.exit(1);
}

mkdirSync(generatedDir, { recursive: true });

// 2. Give the package the module in two forms.
//    - As base64 in a TypeScript module, so that the bytes travel inside the
//      package's JavaScript. Node, Deno, Bun, and browsers load this one, and
//      need no file access and no bundler setting to find it.
//    - As the .wasm file itself, in dist/. Cloudflare Workers loads this one,
//      because a Worker may not compile a module from bytes at run time.
//    package.json picks between the two: see "#wasm-module" there.
const wasm = readFileSync(`${rustDir}/target/${target}/release/text_stats.wasm`);
writeFileSync(
  `${generatedDir}/wasm-bytes.ts`,
  `// Generated by scripts/build.mjs from rust/src/lib.rs. Do not edit.\n` +
    `export const WASM_BASE64: string =\n  '${wasm.toString('base64')}';\n`,
);
mkdirSync(distDir, { recursive: true });
writeFileSync(`${distDir}/text_stats.wasm`, wasm);

// 3. Copy the name and version from package.json, so that the package's
//    __meta export always agrees with its manifest.
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'));
writeFileSync(
  `${generatedDir}/package-info.ts`,
  `// Generated by scripts/build.mjs from package.json. Do not edit.\n` +
    `export const PACKAGE_ID = ${JSON.stringify(pkg.name)};\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export const PACKED_AT = ${Date.now()};\n`,
);

console.log(`Built text_stats.wasm (${wasm.length} bytes) for ${pkg.name}@${pkg.version}`);
